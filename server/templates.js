/** Skill 生成用的 system prompt：要求模型严格按 7 要素输出 JSON */
const skillGenSystemPrompt = `你是一个"企业岗位经验 Skill 生成引擎"。你的任务是把用户用自然语言描述的分析需求，转换成一个结构完整、可直接执行的岗位分析 Skill。

Skill 必须包含以下 7 个要素（缺一不可），并以 JSON 格式输出：

1. name：Skill 名称（简洁、语义明确，如"抖音直播运营复盘"；不要添加任何前缀，也不要包含"Demo-"字样）
2. description：一句话说明该 Skill 做什么、为谁服务
3. scenarios：使用场景对象，包含 role（适用岗位）、timing（适用时机）、preconditions（前置条件）
4. inputDataDef：输入数据定义，数组形式，每项 { field 字段名, type 类型(日期/数值/文本), desc 说明 }
5. analysisFlow：分析流程，字符串数组，是可执行的步骤序列（数据清洗 → 指标计算 → 达成度分析 → 异常归因 → 建议）
6. agentPrompt：Agent 系统提示词，用于驱动 LLM 以该岗位专家口吻执行分析（要求基于数据、引用数字、不编造、给出可执行建议）
7. outputTemplate：输出结果模板，字符串数组，描述报告应包含的章节结构

要求：
- 全部使用简体中文（字段名可以带中文）
- 输入数据定义要具体到字段级，贴合该岗位真实数据形态
- 分析流程必须是可执行步骤，不要写空话
- 严格输出 JSON 对象，不要输出任何其他解释文字`;

/** 报告分析用的 system prompt 模板：把 Skill 的 agentPrompt 和输出模板注入进去 */
function buildReportPrompt(skill, metrics, dataSummary) {
  return [
    {
      role: 'system',
      content: `${skill.agentPrompt}\n\n本次分析的输出必须严格遵循以下报告结构（使用 Markdown 格式，从"## 三、详细分析"章节开始输出）：\n${skill.outputTemplate.map((s, i) => `${i + 1}. ${s}`).join('\n')}\n\n重要纪律：\n1. 只能使用提供给你的数据，不得编造任何数字\n2. 引用数据时写明具体数值\n3. 结论与建议必须可执行，避免空话套话`,
    },
    {
      role: 'user',
      content: `请对以下数据进行专业分析：\n\n【数据概况】\n${dataSummary}\n\n【确定性计算结果】\n${metrics}\n\n请按输出模板要求，输出"三、详细分析"及之后的章节内容（Markdown 格式）。`,
    },
  ];
}

